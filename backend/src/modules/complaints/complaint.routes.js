import { Router } from "express";
import * as c from "./complaint.controller.js";
import { authenticate } from "../../middleware/authenticate.js";
import { validate } from "../../middleware/validate.js";
import { createSchema, updateSchema, commentSchema, listSchema } from "./complaint.validation.js";
const r = Router();
r.use(authenticate);
r.get("/", validate(listSchema, "query"), c.list);
r.post("/", validate(createSchema), c.create);
r.get("/:id", c.get);
r.patch("/:id", validate(updateSchema), c.update);
r.post("/:id/comments", validate(commentSchema), c.addComment);
export default r;
